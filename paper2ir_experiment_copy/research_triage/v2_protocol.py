"""Version 2, open-ended evidence-access protocol.

The original pilot serialises a small claim ledger and asks for a fixed
``action`` enum.  This module is deliberately separate from that protocol:
the model-facing object contains the target paper text, a condition-specific
retrieval interface, and no candidate action list.  The evaluator can still
canonicalise the free-form ``next_step`` after generation.

This module does not call a model or execute retrieval.  A runner may pass
``retrieval_context`` generated by a :class:`final_graph.RetrievalSession`
and persist its trace beside the prompt.  Keeping prompt construction and
post-hoc validation here makes the three-condition pilot auditable before a
provider is enabled.
"""

from __future__ import annotations

import copy
import json
import re
from pathlib import Path
from typing import Any, Iterable

from jsonschema import Draft202012Validator


V2_CONDITIONS = ("paper_only", "external_text", "reasoning_graph")
_PAPER_TOOLS = {"search_paper"}
_TEXT_TOOLS = {"search_paper", "search_external_text"}
_GRAPH_TOOLS = {
    "search_paper",
    "search_external_text",
    "search_claims",
    "expand_neighbors",
    "get_source_anchor",
}


class V2ProtocolError(ValueError):
    """Malformed task, model input, or proposal."""


def _as_nonempty_string(value: Any, name: str) -> str:
    if not isinstance(value, str) or not value.strip():
        raise V2ProtocolError(f"{name} must be a non-empty string")
    return value


def _paper_anchors(task: dict[str, Any]) -> dict[str, dict[str, Any]]:
    """Return target-paper anchors from either supported text representation."""

    paper = task.get("target_paper") or task.get("paper") or {}
    anchors: dict[str, dict[str, Any]] = {}
    raw = paper.get("anchors") if isinstance(paper, dict) else None
    if isinstance(raw, list):
        for item in raw:
            if isinstance(item, dict) and isinstance(item.get("anchor_id"), str):
                anchors[item["anchor_id"]] = item
    elif isinstance(raw, dict):
        for anchor_id, item in raw.items():
            if isinstance(anchor_id, str):
                anchors[anchor_id] = item if isinstance(item, dict) else {"text": str(item)}
    # A segment is an anchor as long as it has a stable id.  This allows a
    # parser to pass the original paper text without first making claim IDs.
    segments = paper.get("segments") if isinstance(paper, dict) else None
    if isinstance(segments, list):
        for item in segments:
            if isinstance(item, dict) and isinstance(item.get("anchor_id"), str):
                anchors.setdefault(item["anchor_id"], item)
    return anchors


def _external_anchors(task: dict[str, Any]) -> dict[str, dict[str, Any]]:
    raw = task.get("external_text") or task.get("external_sources") or []
    result: dict[str, dict[str, Any]] = {}
    if isinstance(raw, list):
        for item in raw:
            if isinstance(item, dict):
                key = item.get("anchor_id") or item.get("source_id")
                if isinstance(key, str) and key:
                    result[key] = item
    elif isinstance(raw, dict):
        for key, item in raw.items():
            if isinstance(key, str):
                result[key] = item if isinstance(item, dict) else {"text": str(item)}
    return result


def _graph_ids(task: dict[str, Any]) -> tuple[set[str], set[str]]:
    graph = task.get("graph") or task.get("reasoning_graph") or {}
    node_ids: set[str] = set()
    edge_ids: set[str] = set()
    if isinstance(graph, dict):
        for node in graph.get("nodes", []):
            if isinstance(node, dict) and isinstance(node.get("node_id") or node.get("id"), str):
                node_ids.add(node.get("node_id") or node.get("id"))
        for edge in graph.get("edges", []):
            if isinstance(edge, dict) and isinstance(edge.get("edge_id") or edge.get("id"), str):
                edge_ids.add(edge.get("edge_id") or edge.get("id"))
    return node_ids, edge_ids


def _required_task_fields(task: dict[str, Any]) -> None:
    if not isinstance(task, dict):
        raise V2ProtocolError("task must be an object")
    _as_nonempty_string(task.get("task_id"), "task_id")
    _as_nonempty_string(task.get("question"), "question")
    _as_nonempty_string(task.get("hypothesis"), "hypothesis")
    paper = task.get("target_paper") or task.get("paper")
    if not isinstance(paper, dict):
        raise V2ProtocolError("task.target_paper must be an object")
    if not (_paper_anchors(task) or isinstance(paper.get("text"), str) and paper.get("text", "").strip()):
        raise V2ProtocolError("target paper must contain full text or anchored segments")


def _condition_tools(condition: str) -> set[str]:
    if condition == "paper_only":
        return _PAPER_TOOLS
    if condition == "external_text":
        return _TEXT_TOOLS
    if condition == "reasoning_graph":
        return _GRAPH_TOOLS
    raise V2ProtocolError(f"unknown v2 condition: {condition}")


def condition_input(
    task: dict[str, Any],
    condition: str,
    *,
    retrieval_context: dict[str, Any] | None = None,
) -> dict[str, Any]:
    """Build the exact JSON object visible to a v2 model.

    The full target paper is preserved in every condition.  External text and
    graph contents are represented by retrieval tools; only a runner-provided
    ``retrieval_context`` is included as returned evidence.  Internal gold
    fields (or legacy claim ledgers/action lists) are never copied into the
    model input.
    """

    _required_task_fields(task)
    if condition not in V2_CONDITIONS:
        raise V2ProtocolError(f"unknown v2 condition: {condition}")
    paper = copy.deepcopy(task.get("target_paper") or task.get("paper"))
    visible: dict[str, Any] = {
        "protocol_version": "2",
        "condition": condition,
        "task_id": task["task_id"],
        "question": task["question"],
        "hypothesis": task["hypothesis"],
        "context": copy.deepcopy(task.get("context", task.get("current_state", {}))),
        "target_paper": paper,
        "execution": copy.deepcopy(task.get("execution", {})),
        "allowed_dataset_refs": list(task.get("allowed_dataset_refs", [])),
        "allowed_entrypoint_refs": list(task.get("allowed_entrypoint_refs", [])),
        "evidence_cutoff": task.get("evidence_cutoff"),
        "knowledge_access": "closed_book",
        "web_tools_enabled": False,
        "retrieval_interface": {
            "tools": sorted(_condition_tools(condition)),
            "max_calls": int(task.get("retrieval", {}).get("max_calls", 8))
            if isinstance(task.get("retrieval"), dict)
            else 8,
            "max_return_tokens": int(task.get("retrieval", {}).get("max_return_tokens", 4000))
            if isinstance(task.get("retrieval"), dict)
            else 4000,
            "graph_snapshot_sha256": (
                (task.get("graph") or {}).get("snapshot_sha256")
                if condition == "reasoning_graph" and isinstance(task.get("graph") or {}, dict)
                else None
            ),
        },
    }
    if condition == "reasoning_graph" and isinstance(task.get("graph"), dict):
        # The complete frozen graph is the backend resource.  The model does
        # not receive a hand-picked answer subgraph in the prompt; it receives
        # the resource identity and must access it through the declared tools.
        visible["retrieval_interface"]["graph_resource"] = {
            "snapshot_file": task["graph"].get("snapshot_file"),
            "node_count": task["graph"].get("node_count"),
            "edge_count": task["graph"].get("edge_count"),
            "access": "full_frozen_graph_via_tools",
        }
    if condition in {"external_text", "reasoning_graph"} and isinstance(task.get("external_corpus"), dict):
        visible["retrieval_interface"]["external_corpus"] = {
            "paper_count": task["external_corpus"].get("paper_count"),
            "manifest_sha256": task["external_corpus"].get("manifest_sha256"),
            "access": "full_frozen_corpus_via_search_external_text",
        }
    if retrieval_context is not None:
        if not isinstance(retrieval_context, dict):
            raise V2ProtocolError("retrieval_context must be an object")
        visible["retrieval_context"] = copy.deepcopy(retrieval_context)
    # Never leak evaluator-only labels, candidate utilities, legacy action
    # enums, or full graph internals into a v2 model prompt.
    return _drop_none(visible)


def build_prompt(
    task: dict[str, Any],
    condition: str,
    *,
    retrieval_context: dict[str, Any] | None = None,
    visible_decision_trace: bool = True,
) -> str:
    """Render a deterministic v2 prompt with free-form next-step output."""

    value = condition_input(task, condition, retrieval_context=retrieval_context)
    skeleton: dict[str, Any] = {
        "protocol_version": "2",
        "task_id": "copy exactly",
        "candidate_next_steps": ["at least two concise candidate directions"],
        "next_step": "one free-form direction; do not use a fixed action label",
        "reason": "short reason, <=500 characters",
        "evidence": [
            {
                "ref_type": "paper_anchor|external_text|graph_node|graph_edge",
                "ref_id": "returned or visible reference id",
                "role": "support|limitation|context",
            }
        ],
        "conditions": [{"key": "condition key", "value": "value held fixed or varied"}],
        "experiment_card": {
            "baseline": "...",
            "treatment": "...",
            "controls": ["..."],
            "metrics": ["..."],
            "entrypoint": None,
            "expected_observation": "...",
            "falsifier": "...",
            "budget": {"max_seconds": 0, "max_gpu_hours": 0},
        },
        "decision_rule": "what result changes the next choice",
        "uncertainty": "scope limitation or missing evidence",
        "retrieval_trace": [
            {
                "tool": "tool name",
                "arguments": {},
                "returned_ids": [],
                "purpose": "why this query was made",
            }
        ],
    }
    # Retrieval trace is a protocol audit field rather than hidden reasoning,
    # so it remains required even when a caller chooses not to show a longer
    # decision trace.  ``visible_decision_trace`` is retained as a forward
    # compatible argument for runners that share their v1 flags.
    instructions = [
        "You choose the next experiment for a scientific task.",
        "The target_paper is the full paper text. Use only the visible paper and returned retrieval context; do not use web search or pretrained facts as evidence.",
        "Generate at least two plausible candidate_next_steps, then select one free-form next_step. Do not select from a supplied action enum and do not invent a candidate id.",
        "Cite only references that are present in the paper or returned by a retrieval call. Graph nodes and edges do not receive provenance credit when their source anchor is unavailable.",
        "The experiment_card is your output, not an input candidate. State baseline, treatment, controls, metrics, expected observation, falsifier, and budget.",
        "Return exactly one JSON object matching OUTPUT_SKELETON. Do not include hidden chain-of-thought.",
    ]
    return (
        "\n".join(instructions)
        + "\n\nOUTPUT_SKELETON:\n"
        + json.dumps(skeleton, ensure_ascii=False, indent=2)
        + "\n\nTASK_INPUT:\n"
        + json.dumps(value, ensure_ascii=False, sort_keys=True, indent=2)
        + "\n"
    )


def canonicalise_next_step(next_step: str) -> str | None:
    """Map free text to a descriptive category *after* generation.

    This is evaluator metadata only.  It is intentionally absent from the
    model-facing schema and is never required for a valid v2 card.
    """

    if not isinstance(next_step, str):
        return None
    text = next_step.casefold()
    patterns = (
        ("abstain", ("暂缓", "无法判断", "不确定", "abstain", "insufficient evidence")),
        ("reproduce", ("复现", "reproduce", "replicate")),
        ("ablate", ("消融", "ablation", "ablate")),
        ("contrast", ("对照", "比较", "contrast", "compare", "factorial")),
        ("seek_independent_evidence", ("独立证据", "independent", "外部验证", "external evidence")),
    )
    for label, words in patterns:
        if any(word in text for word in words):
            return label
    return None


def _schema_errors(proposal: dict[str, Any]) -> list[str]:
    path = Path(__file__).with_name("schema") / "proposal_v2.schema.json"
    validator = Draft202012Validator(json.loads(path.read_text(encoding="utf-8")))
    return [f"schema: {e.json_path}: {e.message}" for e in validator.iter_errors(proposal)]


def _visible_reference_ids(task: dict[str, Any], condition: str) -> dict[str, set[str]]:
    paper = set(_paper_anchors(task))
    external = set(_external_anchors(task)) if condition in {"external_text", "reasoning_graph"} else set()
    nodes, edges = _graph_ids(task) if condition == "reasoning_graph" else (set(), set())
    return {"paper_anchor": paper, "external_text": external, "graph_node": nodes, "graph_edge": edges}


def _trace_returned_ids(trace: Iterable[Any]) -> set[str]:
    result: set[str] = set()
    for item in trace:
        if isinstance(item, dict):
            values = item.get("returned_ids", [])
            if isinstance(values, list):
                result.update(value for value in values if isinstance(value, str))
    return result


def validate_v2(
    task: dict[str, Any],
    proposal: dict[str, Any],
    condition: str,
    *,
    actual_retrieval_trace: list[dict[str, Any]] | None = None,
) -> dict[str, Any]:
    """Validate a free-form v2 card and retrieval/evidence closure.

    This does not judge whether a proposed experiment is scientifically good;
    that requires blind human or executable evaluation.  It only checks that
    references came from the condition's visible evidence and that the card
    is auditable.
    """

    errors: list[str] = []
    warnings: list[str] = []
    if condition not in V2_CONDITIONS:
        return {"ok": False, "errors": [f"unknown condition: {condition}"], "warnings": [], "metrics": {}}
    if not isinstance(proposal, dict):
        return {"ok": False, "errors": ["proposal must be an object"], "warnings": [], "metrics": {}}
    errors.extend(_schema_errors(proposal))
    if errors:
        return {"ok": False, "errors": errors, "warnings": [], "metrics": {"schema_valid": False}}
    if proposal.get("task_id") != task.get("task_id"):
        errors.append("task_id does not match task")
    if "action" in proposal:
        errors.append("v2 proposal must use free-form next_step; action is model-facing legacy syntax")
    allowed = _visible_reference_ids(task, condition)
    trace = proposal.get("retrieval_trace", [])
    # A model can fabricate a returned_ids list.  When the runner has a
    # session trace, use that hidden trace as the authority for evidence
    # closure.  The model-facing JSON still records its own trace so the
    # discrepancy remains inspectable.
    trace_for_closure = actual_retrieval_trace if actual_retrieval_trace is not None else trace
    tools = _condition_tools(condition)
    trace_ids = _trace_returned_ids(trace_for_closure)
    for index, call in enumerate(trace):
        if not isinstance(call, dict):
            continue
        tool = call.get("tool")
        if tool not in tools:
            errors.append(f"retrieval_trace[{index}] tool is unavailable in {condition}: {tool}")
    refs = proposal.get("evidence", [])
    for index, ref in enumerate(refs):
        if not isinstance(ref, dict):
            continue
        ref_type, ref_id = ref.get("ref_type"), ref.get("ref_id")
        if ref_type not in allowed or ref_id not in allowed.get(ref_type, set()):
            errors.append(f"evidence[{index}] cites unavailable {ref_type}:{ref_id}")
        elif ref_type != "paper_anchor" and ref_id not in trace_ids:
            errors.append(f"evidence[{index}] cites {ref_id} without a retrieval_trace return")
    paper_refs = {ref.get("ref_id") for ref in refs if isinstance(ref, dict) and ref.get("ref_type") == "paper_anchor"}
    if any(ref.get("ref_type") == "graph_node" for ref in refs if isinstance(ref, dict)):
        if not task.get("graph_provenance_available", False):
            warnings.append("graph node provenance is unavailable; graph citations cannot receive evidence credit")
    if not refs and proposal.get("next_step"):
        warnings.append("next_step has no evidence references")
    if not paper_refs and not any(ref.get("ref_type") in {"external_text", "graph_node", "graph_edge"} for ref in refs if isinstance(ref, dict)):
        warnings.append("card has no paper or retrieved evidence")
    return {
        "ok": not errors,
        "errors": errors,
        "warnings": warnings,
        "metrics": {
            "schema_valid": True,
            "candidate_count": len(proposal.get("candidate_next_steps", [])),
            "evidence_count": len(refs),
            "retrieval_call_count": len(trace),
            "retrieval_return_count": len(trace_ids),
            "retrieval_trace_verified": actual_retrieval_trace is not None,
            "canonical_action": canonicalise_next_step(proposal.get("next_step", "")),
            "has_falsifier": bool((proposal.get("experiment_card") or {}).get("falsifier")),
        },
    }


def _drop_none(value: Any) -> Any:
    if isinstance(value, dict):
        return {k: _drop_none(v) for k, v in value.items() if v is not None}
    if isinstance(value, list):
        return [_drop_none(item) for item in value]
    return value
